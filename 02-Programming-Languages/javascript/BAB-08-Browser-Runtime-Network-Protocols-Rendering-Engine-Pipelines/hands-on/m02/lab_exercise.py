def main():
    print(f"{CLR_BOLD}{CLR_GREEN}======================================================================{CLR_RESET}")
    print(f"{CLR_BOLD}{CLR_GREEN}  DEEP DIVE: BROWSER RUNTIME, PROTOCOLS & RENDERING PIPELINES LAB     {CLR_RESET}")
    print(f"{CLR_BOLD}{CLR_GREEN}======================================================================{CLR_RESET}")

    # 1. NETWORK PHASE: Multiplexed Stream Extraction
    net = HTTP2Multiplexer()
    # Stream 1: HTML Document chunks
    net.push_frame(1, "HTML", 0, 2, "<html><body><header id='hero'></header>")
    net.push_frame(1, "HTML", 1, 2, "<div class='card'><button id='cta'>Click</button></div></body></html>")
    # Stream 2: CSS Stylesheet chunks interleaved
    net.push_frame(2, "CSS", 0, 2, "body { width: 1024; } header { height: 120; } ")
    net.push_frame(2, "CSS", 1, 2, ".card { height: 300; width: 600; } #cta { height: 45; width: 150; }")
    
    resources = net.process_network_stream()

    # 2. RENDERING PIPELINE PHASE
    renderer = RenderingEngine()
    dom_root = renderer.parse_mock_dom(resources["HTML"])

    css_rules = {
        "body": {"width": 1024.0, "height": 800.0, "color": "#111111"},
        "#hero": {"width": 1024.0, "height": 120.0, "color": "#0055ff"},
        ".card": {"width": 600.0, "height": 300.0, "color": "#ffffff"},
        "#cta": {"width": 150.0, "height": 45.0, "color": "#00ff66"},
    }
    renderer.apply_cssom_cascade(dom_root, css_rules)

    print(f"\n{CLR_BOLD}{CLR_BLUE}=== Pipeline Stage 3: Layout Tree Geometry (Reflow) ==={CLR_RESET}")
    layout_root = renderer.build_layout_tree(dom_root)

    def print_layout(box: LayoutBox, level: int = 0):
        r = box.box_rect
        print(f"{'  ' * level}Box [{CLR_CYAN}{box.node.tag}{CLR_RESET}] -> "
              f"X: {r.x:5.1f} | Y: {r.y:5.1f} | W: {r.width:6.1f} | H: {r.height:5.1f}")
        for c in box.children:
            print_layout(c, level + 1)

    print_layout(layout_root)

    print(f"\n{CLR_BOLD}{CLR_BLUE}=== Pipeline Stage 4: Paint & Display List Generation ==={CLR_RESET}")
    display_list = renderer.paint(layout_root)
    for cmd in display_list:
        print(f"{CLR_GRAY}[RASTER CMD]{CLR_RESET} {cmd}")

    # 3. RUNTIME / EVENT LOOP EXECUTION PHASE
    loop = EventLoop()

    def user_script(ev: EventLoop):
        print("  [JS Stack] Line 1: console.log('Sync start')")
        
        # Scheduling setTimeout (Macrotask)
        ev.schedule("setTimeout(..., 0)", TaskType.MACRO, 
                    lambda: print("  [Task Body] Executing Timer Handler"))
        
        # Scheduling Promise.then (Microtask)
        ev.schedule("Promise.resolve().then(Callback1)", TaskType.MICRO,
                    lambda: print("  [Microtask Body] Promise 1 Resolved"))

        # Nested Microtask inside script
        ev.schedule("Promise.resolve().then(Callback2)", TaskType.MICRO,
                    lambda: ev.schedule("queueMicrotask(Chained)", TaskType.MICRO, 
                                        lambda: print("  [Microtask Body] Chained microtask handled!")))
        
        # Request Reflow / Invalidation
        ev.render_requested = True
        print("  [JS Stack] Line 4: Mutate DOM (Triggering Layout Request)")
        print("  [JS Stack] Line 5: console.log('Sync end')")

    loop.execute_script("bundle.app.js", user_script)

    # Simulate browser cycles (Ticks)
    loop.run_tick()
    loop.run_tick()

    print(f"\n{CLR_BOLD}{CLR_GREEN}Pipeline Execution Summary:{CLR_RESET}")
    print(f" - Parsed DOM nodes: {CLR_BOLD}5{CLR_RESET}")
    print(f" - CSS Cascade rules applied: {CLR_BOLD}{len(css_rules)}{CLR_RESET}")
    print(f" - Display list commands generated: {CLR_BOLD}{len(display_list)}{CLR_RESET}")
    print(f" - State: Main thread execution completed without unhandled rejections.\n")

if __name__ == "__main__":
    main()