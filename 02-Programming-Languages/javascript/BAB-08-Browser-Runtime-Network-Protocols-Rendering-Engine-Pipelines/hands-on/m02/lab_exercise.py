# MODULE 2: HTTP/2 MULTIPLEXED NETWORK LOADER SIMULATION
# ============================================================================

@dataclass
class NetworkFrame:
    stream_id: int
    payload_type: str
    chunk_id: int
    total_chunks: int
    data: str

class HTTP2Multiplexer:
    """Simulates multiplexed binary framing over a single TCP connection."""
    def __init__(self):
        self.frames: deque[NetworkFrame] = deque()
        self.reassembled_streams: Dict[int, List[str]] = {}

    def push_frame(self, stream_id: int, payload_type: str, chunk_id: int, total_chunks: int, data: str):
        self.frames.append(NetworkFrame(stream_id, payload_type, chunk_id, total_chunks, data))

    def process_network_stream(self) -> Dict[str, str]:
        print(f"\n{CLR_BOLD}{CLR_BLUE}=== HTTP/2 Multiplexed Network Engine ==={CLR_RESET}")
        resources: Dict[str, str] = {}
        type_mapping: Dict[int, str] = {}

        while self.frames:
            frame = self.frames.popleft()
            type_mapping[frame.stream_id] = frame.payload_type
            if frame.stream_id not in self.reassembled_streams:
                self.reassembled_streams[frame.stream_id] = ["" for _ in range(frame.total_chunks)]
            
            self.reassembled_streams[frame.stream_id][frame.chunk_id] = frame.data
            print(f"{CLR_GRAY}[TCP/IP]{CLR_RESET} Frame received: Stream {frame.stream_id} "
                  f"({frame.payload_type}) [{frame.chunk_id + 1}/{frame.total_chunks}]")

        for s_id, chunks in self.reassembled_streams.items():
            r_type = type_mapping[s_id]
            resources[r_type] = "".join(chunks)
            print(f"{CLR_GREEN}* Resource fully reassembled:{CLR_RESET} {r_type} ({len(resources[r_type])} bytes)")
        
        return resources

