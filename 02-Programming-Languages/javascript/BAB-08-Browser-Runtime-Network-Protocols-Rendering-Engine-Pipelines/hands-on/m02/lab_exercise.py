# MODULE 1: JAVASCRIPT EVENT LOOP SIMULATOR (WHATWG SPECIFICATION MAPPING)
# ============================================================================

class TaskType(Enum):
    MACRO = auto()   # setTimeout, setInterval, I/O
    MICRO = auto()   # Promise callbacks, queueMicrotask, MutationObserver

@dataclass
class Task:
    name: str
    task_type: TaskType
    action: Callable[[], None]

class EventLoop:
    """
    Simulates WHATWG Browser Event Loop:
    1. Execute synchronous call-stack.
    2. Drain microtask queue entirely before yielding to rendering.
    3. Execute single macrotask from task queue.
    4. Trigger rendering pipeline opportunity.
    """
    def __init__(self):
        self.call_stack: List[str] = []
        self.microtask_queue: deque[Task] = deque()
        self.macrotask_queue: deque[Task] = deque()
        self.render_requested: bool = False

    def schedule(self, name: str, task_type: TaskType, action: Callable[[], None]) -> None:
        task = Task(name, task_type, action)
        if task_type == TaskType.MICRO:
            self.microtask_queue.append(task)
            print(f"{CLR_GRAY}[V8 Engine]{CLR_RESET} Enqueued Microtask: {CLR_CYAN}{name}{CLR_RESET}")
        else:
            self.macrotask_queue.append(task)
            print(f"{CLR_GRAY}[V8 Engine]{CLR_RESET} Enqueued Macrotask: {CLR_YELLOW}{name}{CLR_RESET}")

    def execute_script(self, script_name: str, script_fn: Callable[['EventLoop'], None]) -> None:
        print(f"\n{CLR_BOLD}{CLR_BLUE}=== Executing Initial Script (Main Thread): {script_name} ==={CLR_RESET}")
        self.call_stack.append(script_name)
        script_fn(self)
        self.call_stack.pop()

    def run_tick(self) -> None:
        print(f"\n{CLR_BOLD}{CLR_MAGENTA}--- Processing Event Loop Tick ---{CLR_RESET}")
        
        # 1. Drain ALL microtasks
        while self.microtask_queue:
            task = self.microtask_queue.popleft()
            print(f"{CLR_CYAN}  -> Executing Microtask:{CLR_RESET} {task.name}")
            task.action()

        # 2. Check if rendering pipeline update is needed
        if self.render_requested:
            print(f"{CLR_GREEN}  -> [Render Opportunity Hook Triggered]{CLR_RESET}")
            self.render_requested = False

        # 3. Execute ONE macrotask
        if self.macrotask_queue:
            task = self.macrotask_queue.popleft()
            print(f"{CLR_YELLOW}  -> Executing Macrotask:{CLR_RESET} {task.name}")
            task.action()

            # Drain any microtasks generated by this macrotask
            while self.microtask_queue:
                mtask = self.microtask_queue.popleft()
                print(f"{CLR_CYAN}    -> Sub-Microtask:{CLR_RESET} {mtask.name}")
                mtask.action()

