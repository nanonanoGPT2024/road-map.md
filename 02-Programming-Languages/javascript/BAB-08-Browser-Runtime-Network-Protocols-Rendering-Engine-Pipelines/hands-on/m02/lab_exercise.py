@dataclass
class DOMNode:
    tag: str
    attributes: Dict[str, str] = field(default_factory=dict)
    children: List['DOMNode'] = field(default_factory=list)
    computed_styles: Dict[str, Any] = field(default_factory=dict)

@dataclass
class Rect:
    x: float
    y: float
    width: float
    height: float

@dataclass
class LayoutBox:
    node: DOMNode
    box_rect: Rect = field(default_factory=lambda: Rect(0, 0, 0, 0))
    children: List['LayoutBox'] = field(default_factory=list)

class RenderingEngine:
    """Simulates Blink/WebKit core: DOM Parser, CSS Cascade, Layout Tree & Rasterizer."""

    def parse_mock_dom(self, html: str) -> DOMNode:
        """Tokenize mock nested HTML: <tag attr='val'>...</tag>."""
        print(f"\n{CLR_BOLD}{CLR_BLUE}=== Pipeline Stage 1: HTML Parsing & DOM Construction ==={CLR_RESET}")
        root = DOMNode(tag="html")
        body = DOMNode(tag="body")
        header = DOMNode(tag="header", attributes={"id": "hero"})
        content = DOMNode(tag="div", attributes={"class": "card"})
        button = DOMNode(tag="button", attributes={"id": "cta"})

        content.children.append(button)
        body.children.extend([header, content])
        root.children.append(body)

        def print_dom(node: DOMNode, indent: int = 0):
            attrs = " ".join([f'{k}="{v}"' for k, v in node.attributes.items()])
            attr_str = f" {attrs}" if attrs else ""
            print(f"{'  ' * indent}{CLR_YELLOW}<{node.tag}{attr_str}>{CLR_RESET}")
            for child in node.children:
                print_dom(child, indent + 1)

        print_dom(root)
        return root

    def apply_cssom_cascade(self, root: DOMNode, css_rules: Dict[str, Dict[str, Any]]) -> None:
        """Computes matching styles per node using specificity cascade emulation."""
        print(f"\n{CLR_BOLD}{CLR_BLUE}=== Pipeline Stage 2: CSSOM Match & Style Computation ==={CLR_RESET}")
        
        def match_and_compute(node: DOMNode):
            # Base default browser styles
            node.computed_styles = {"display": "block", "width": 800.0, "height": 40.0, "color": "#000"}

            # Selector rule matching
            if node.tag in css_rules:
                node.computed_styles.update(css_rules[node.tag])
            if "id" in node.attributes and f"#{node.attributes['id']}" in css_rules:
                node.computed_styles.update(css_rules[f"#{node.attributes['id']}"])
            if "class" in node.attributes and f".{node.attributes['class']}" in css_rules:
                node.computed_styles.update(css_rules[f".{node.attributes['class']}"])

            print(f"Computed Style [{CLR_CYAN}{node.tag}{CLR_RESET}]: "
                  f"display={node.computed_styles.get('display')}, "
                  f"width={node.computed_styles.get('width')}, "
                  f"height={node.computed_styles.get('height')}")

            for child in node.children:
                match_and_compute(child)

        match_and_compute(root)

    def build_layout_tree(self, node: DOMNode, cursor_y: float = 0.0) -> LayoutBox:
        """Reflow/Layout: Calculates explicit geometric coordinates (x, y, w, h)."""
        box = LayoutBox(node=node)
        width = float(node.computed_styles.get("width", 800.0))
        height = float(node.computed_styles.get("height", 40.0))
        
        box.box_rect = Rect(x=0.0, y=cursor_y, width=width, height=height)
        current_y = cursor_y

        for child in node.children:
            child_box = self.build_layout_tree(child, current_y)
            box.children.append(child_box)
            current_y += child_box.box_rect.height  # standard normal flow block accumulation

        return box

    def paint(self, layout_root: LayoutBox) -> List[str]:
        """Generates Display List for the Skia rasterization layer."""
        display_list = []

        def traverse_paint(lbox: LayoutBox):
            r = lbox.box_rect
            tag = lbox.node.tag
            color = lbox.node.computed_styles.get("color", "#000000")
            display_list.append(f"DRAW_RECT x={r.x:.1f}, y={r.y:.1f}, w={r.width:.1f}, h={r.height:.1f} tag=<{tag}>")
            display_list.append(f"SET_BRUSH color={color}")
            for child in lbox.children:
                traverse_paint(child)

        traverse_paint(layout_root)
        return display_list

