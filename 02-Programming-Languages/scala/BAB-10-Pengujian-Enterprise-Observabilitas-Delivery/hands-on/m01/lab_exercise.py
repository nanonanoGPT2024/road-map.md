# 3. DELIVERY & CI/CD DEPLOYMENT PIPELINE
# ==============================================================================

class DeliveryPipeline:
    def __init__(self, artifact_name: str, version: str):
        self.artifact_name = artifact_name
        self.version = version

    def run_stage(self, stage_name: str, delay: float = 0.25) -> bool:
        sys.stdout.write(f"  {Color.YELLOW}⏳ [{stage_name}] In progress...{Color.RESET}")
        sys.stdout.flush()
        time.sleep(delay)
        sys.stdout.write(f"\r  {Color.GREEN}✔ [{stage_name}] COMPLETED!{Color.RESET}\n")
        return True

    def canary_rollout(self, steps: List[int]):
        print(f"\n  {Color.BOLD}{Color.MAGENTA}>>> Initiating Kubernetes Canary Deployment (Argo Rollouts) <<<{Color.RESET}")
        for percentage in steps:
            bar_len = percentage // 4
            bar = f"{Color.BG_GREEN}{' ' * bar_len}{Color.RESET}{' ' * (25 - bar_len)}"
            print(f"  [{bar}] {Color.BOLD}{percentage}% traffic directed to v{self.version}{Color.RESET} (Canary health: 200 OK)")
            time.sleep(0.2)

