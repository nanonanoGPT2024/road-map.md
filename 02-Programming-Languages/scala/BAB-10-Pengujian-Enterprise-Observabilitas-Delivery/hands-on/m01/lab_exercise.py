@dataclass
class TestResult:
    spec_name: str
    assertion: str
    passed: bool
    latency_ms: float
    error_msg: Optional[str] = None

class ScalaTestEngine:
    def __init__(self):
        self.results: List[TestResult] = []

    def flat_spec(self, behavior: str, test_fn: Callable[[], bool]):
        t0 = time.perf_counter()
        passed = False
        err = None
        try:
            passed = test_fn()
        except Exception as e:
            err = str(e)
            passed = False
        elapsed = (time.perf_counter() - t0) * 1000.0
        result = TestResult(spec_name=behavior, assertion="should conform to spec", passed=passed, latency_ms=elapsed, error_msg=err)
        self.results.append(result)
        return result

    def scalacheck_property(self, prop_name: str, sample_size: int, property_fn: Callable[[int], bool]):
        t0 = time.perf_counter()
        passed = True
        failing_seed = None
        for i in range(sample_size):
            sample = random.randint(-1000, 1000)
            if not property_fn(sample):
                passed = False
                failing_seed = sample
                break
        elapsed = (time.perf_counter() - t0) * 1000.0
        
        err = None
        if not passed:
            # Simulate shrinking to minimal falsified counter-example
            err = f"Falsified after sample count! Counterexample: {failing_seed} (Shrunk -> 0)"
        
        result = TestResult(
            spec_name=f"Property: {prop_name} ({sample_size} runs)",
            assertion="forAll samples generated by Gen[Int]",
            passed=passed,
            latency_ms=elapsed,
            error_msg=err
        )
        self.results.append(result)
        return result

