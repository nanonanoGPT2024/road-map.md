@dataclass
class Span:
    trace_id: str
    span_id: str
    parent_span_id: Optional[str]
    name: str
    duration_ms: float
    attributes: Dict[str, Any] = field(default_factory=dict)
    status: str = "OK"

class OpenTelemetryTracer:
    def __init__(self, service_name: str):
        self.service_name = service_name
        self.spans: List[Span] = []
        self.metrics_counters: Dict[str, int] = {}
        self.metrics_latency: Dict[str, List[float]] = {}

    def new_trace_id(self) -> str:
        return uuid.uuid4().hex[:16]

    def new_span_id(self) -> str:
        return uuid.uuid4().hex[:8]

    def record_metric(self, name: str, value: float):
        if name not in self.metrics_latency:
            self.metrics_latency[name] = []
            self.metrics_counters[name] = 0
        self.metrics_counters[name] += 1
        self.metrics_latency[name].append(value)

    def create_span(self, trace_id: str, name: str, parent_id: Optional[str] = None, duration_ms: float = 15.0, attrs: Dict[str, Any] = None) -> Span:
        span = Span(
            trace_id=trace_id,
            span_id=self.new_span_id(),
            parent_span_id=parent_id,
            name=name,
            duration_ms=duration_ms,
            attributes=attrs or {"service.name": self.service_name}
        )
        self.spans.append(span)
        self.record_metric(f"{self.service_name}.span.duration", duration_ms)
        return span

