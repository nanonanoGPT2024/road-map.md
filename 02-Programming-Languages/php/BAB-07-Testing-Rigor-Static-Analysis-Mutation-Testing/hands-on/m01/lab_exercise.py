def original_discount_calc(cart_total: float, is_vip: bool) -> float:
    if cart_total <= 0.0:
        return 0.0
    discount = 0.0
    if cart_total >= 100.0 and is_vip:
        discount = cart_total * 0.15
    elif cart_total >= 50.0:
        discount = cart_total * 0.05
    return round(discount, 2)


# --- Mutants (Generated by Infection PHP Simulation) ---

def mutant_1_boundary_negation(cart_total: float, is_vip: bool) -> float:
    """Mutator: GreaterThanOrEqualTo -> GreaterThan ($cartTotal > 100.0)"""
    if cart_total <= 0.0:
        return 0.0
    discount = 0.0
    if cart_total > 100.0 and is_vip:  # Mutated: >= replaced with >
        discount = cart_total * 0.15
    elif cart_total >= 50.0:
        discount = cart_total * 0.05
    return round(discount, 2)


def mutant_2_logical_operator(cart_total: float, is_vip: bool) -> float:
    """Mutator: LogicalAnd -> LogicalOr ($cartTotal >= 100.0 || $isVip)"""
    if cart_total <= 0.0:
        return 0.0
    discount = 0.0
    if cart_total >= 100.0 or is_vip:  # Mutated: && replaced with ||
        discount = cart_total * 0.15
    elif cart_total >= 50.0:
        discount = cart_total * 0.05
    return round(discount, 2)


def mutant_3_return_value_removal(cart_total: float, is_vip: bool) -> float:
    """Mutator: EarlyReturn0 -> EarlyReturn1 (if $cartTotal <= 0 return 1.0)"""
    if cart_total <= 0.0:
        return 1.0  # Mutated: return 0.0 replaced with 1.0
    discount = 0.0
    if cart_total >= 100.0 and is_vip:
        discount = cart_total * 0.15
    elif cart_total >= 50.0:
        discount = cart_total * 0.05
    return round(discount, 2)


def mutant_4_arithmetic_subtraction(cart_total: float, is_vip: bool) -> float:
    """Mutator: MultiplierReplacement (0.15 -> 0.10)"""
    if cart_total <= 0.0:
        return 0.0
    discount = 0.0
    if cart_total >= 100.0 and is_vip:
        discount = cart_total * 0.10  # Mutated: 0.15 replaced with 0.10
    elif cart_total >= 50.0:
        discount = cart_total * 0.05
    return round(discount, 2)


def mutant_5_lower_boundary(cart_total: float, is_vip: bool) -> float:
    """Mutator: GreaterThanOrEqualTo -> GreaterThan ($cartTotal > 50.0)"""
    if cart_total <= 0.0:
        return 0.0
    discount = 0.0
    if cart_total >= 100.0 and is_vip:
        discount = cart_total * 0.15
    elif cart_total > 50.0:  # Mutated: >= replaced with >
        discount = cart_total * 0.05
    return round(discount, 2)


